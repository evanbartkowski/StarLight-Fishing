/**
 * Rolls for an aberration variant of a caught fish species
 * @param {string} speciesId
 * @param {object} options
 * @returns {object|null}
 */
export function rollAberration(speciesId, options = {}) {
  const aberration = ABERRATIONS_CATALOG[speciesId];
  if (!aberration) return null;

  // Baseline chance: 4.0%
  let chance = options.chance || 0.04;

  // Dark zones / night / thunderstorm bonus
  if (options.isNight) chance += 0.02;
  if (options.isThunderstorm) chance += 0.03;
  if (options.zoneTier && options.zoneTier >= 3) chance += 0.02;

  if (Math.random() < chance) {
    return { ...aberration };
  }
  return null;
}
